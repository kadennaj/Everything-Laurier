import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import './build-map-search.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const mapRoot=path.join(root,'indoor-campus-map');
const require=createRequire(path.join(mapRoot,'package.json'));
const { build }=require('vite');
const references={};
for(const file of ['indoors.json','new-indoors.json']) {
 for(const building of JSON.parse(await readFile(path.join(mapRoot,'src/data',file),'utf8'))) {
  for(const floor of building.floors) {
   const name=floor.blueprint;
   const native=path.join(root,'assets/campus-map',name);
   const web=path.join(root,'public/campus-map',name);
   await mkdir(path.dirname(native),{recursive:true});await mkdir(path.dirname(web),{recursive:true});
   await copyFile(path.join(mapRoot,'public',name),native);await copyFile(native,web);
   references[name]=`../../assets/campus-map${name}`;
  }
 }
}
const output=await build({root:mapRoot,configFile:false,build:{write:false,minify:true,lib:{entry:path.join(mapRoot,'src/main.tsx'),name:'CampusMap',formats:['iife']},rollupOptions:{output:{inlineDynamicImports:true}}},define:{'process.env.NODE_ENV':'"production"'}});
const files=(Array.isArray(output)?output:[output]).flatMap(result=>result.output);
const js=files.filter(f=>f.type==='chunk').map(f=>f.code).join('\n');
const css=files.filter(f=>f.type==='asset'&&f.fileName.endsWith('.css')).map(f=>String(f.source)).join('\n');
// The renderer is inline. Floor plan images load on demand from bundled assets.
const html=`<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="referrer" content="no-referrer"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src 'self' data:; connect-src 'none'; font-src data:; base-uri 'none'; form-action 'none'"><style>${css}</style></head><body><div id="root"></div><script>${js.replace(/<\/script/gi,'<\\/script')}</script></body></html>`;
await mkdir(path.join(root,'src/generated'),{recursive:true});
await writeFile(path.join(root,'public/campus-map/index.html'),html);
await writeFile(path.join(root,'src/generated/campus-map.ts'),'// Generated by scripts/build-map.mjs; edit the source, then rebuild.\nexport default '+JSON.stringify(html)+';\n');
await writeFile(path.join(root,'src/generated/campus-map-assets.ts'),'// Generated by scripts/build-map.mjs.\nexport const mapAssets: Record<string,number> = {\n'+Object.entries(references).map(([name,file])=>JSON.stringify(name)+': require('+JSON.stringify(file)+'),').join('\n')+'\n};\n');
console.log(`Embedded map: ${Object.keys(references).length} source floor plans, ${(html.length/1024/1024).toFixed(1)} MB, no runtime CDN.`);
